# frozen_string_literal: true

require "cgi"
require_relative "sanitize"

module PHP2ShellPOC2026
  # Fingerprints the page an edge returns instead of the application. A 403
  # is not a patch verdict, but the page that produced it is still evidence:
  # "OVHcloud blocked suspicious activity" tells the operator that the scan
  # never reached PHP, while "Sucuri Website Firewall" tells them which
  # control answered. This turns a dead-end UNKNOWN into a next step.
  module BlockPage
    Result = Struct.new(:vendor, :summary, :title, :ua_sensitive, :status,
                        keyword_init: true) do
      def to_h
        {
          vendor: vendor,
          summary: summary,
          title: title,
          ua_sensitive: ua_sensitive,
          status: status
        }
      end
    end

    VENDORS = [
      {
        name: "OVHcloud",
        header: /x-ovh-webhosting-id/i,
        body: /OVHcloud|Request blocked due to suspicious activity/i,
        summary: /Request blocked due to ([^.!?]+)/i,
        ua_sensitive: true
      },
      {
        name: "Cloudflare",
        header: /cf-ray|cf-mitigated/i,
        body: /Cloudflare Ray ID|Attention Required!?\s*\|?\s*Cloudflare|cf-error-details/i,
        summary: /Cloudflare Ray ID:\s*([0-9a-f]+)/i,
        ua_sensitive: true
      },
      {
        name: "Akamai",
        header: /akamai-grn/i,
        body: /Reference #\d+\.[0-9a-f]+|AkamaiGHost/i,
        summary: /Reference #(\d+\.[0-9a-f]+)/i,
        ua_sensitive: true
      },
      {
        name: "Sucuri",
        header: /x-sucuri-id/i,
        body: /Sucuri Website Firewall|Access Denied - Sucuri/i,
        summary: nil,
        ua_sensitive: true
      },
      {
        name: "Imperva",
        header: /x-iinfo/i,
        body: /Incapsula incident ID|_Incapsula_Resource|Incapsula/i,
        summary: /Incapsula incident ID:?\s*([\w-]+)/i,
        ua_sensitive: true
      },
      {
        name: "AWS WAF",
        header: /x-amzn-waf-action/i,
        body: /AWS WAF|Request blocked by AWS/i,
        summary: nil,
        ua_sensitive: true
      },
      {
        name: "F5 BIG-IP",
        header: /x-wa-info/i,
        body: /The requested URL was rejected|support ID/i,
        summary: /Support ID:?\s*([\w-]+)/i,
        ua_sensitive: true
      },
      {
        name: "Wordfence",
        header: nil,
        body: /Wordfence/i,
        summary: nil,
        ua_sensitive: true
      },
      {
        name: "ModSecurity",
        header: nil,
        body: /ModSecurity|Mod_Security|generated by Mod_Security/i,
        summary: nil,
        ua_sensitive: true
      }
    ].freeze

    def self.analyze(probes, access: nil)
      state = access&.state
      return nil if state && !%i[blocked restricted rate_limited server_error].include?(state)

      probe = probes.find(&:denied?) || probes.find(&:rate_limited?) || probes.find(&:server_error?)
      return nil unless probe

      title = probe.title
      body  = probe.text_body.to_s
      match = VENDORS.find { |vendor| vendor_match?(vendor, probe, body) }

      if match
        summary = vendor_summary(match, body, title)
        return Result.new(vendor: match[:name], summary: summary, title: title,
                          ua_sensitive: match[:ua_sensitive], status: probe.status)
      end

      # A generic 403 still tells the operator that an edge, not PHP, answered.
      # Do not manufacture a vendor, but do capture a useful title/sentence.
      return nil unless state.nil? || state == :blocked || probe.rate_limited? || probe.server_error?

      summary = [title, first_sentence(body)].compact.find { |text| text.length >= 8 }
      summary ||= "HTTP #{probe.status}"
      Result.new(vendor: nil, summary: summary, title: title,
                 ua_sensitive: probe.denied?, status: probe.status)
    end

    def self.vendor_match?(vendor, probe, body)
      header_match = vendor[:header] && probe.headers.keys.any? { |name| name.match?(vendor[:header]) }
      header_match || body.match?(vendor[:body])
    end
    private_class_method :vendor_match?

    def self.vendor_summary(vendor, body, title)
      if vendor[:summary]
        match = body.match(vendor[:summary])
        if match
          summary = if vendor[:name] == "OVHcloud"
                      "Request blocked due to #{match[1]}"
                    else
                      "Blocked (#{match[1]})"
                    end
          return Sanitize.terminal(summary, max: 180)
        end
      end

      case vendor[:name]
      when "OVHcloud"
        "Request blocked due to suspicious activity"
      when "Cloudflare"
        title || "Cloudflare challenge or block page"
      when "Akamai"
        "Akamai edge reference"
      when "Sucuri"
        "Sucuri Website Firewall block page"
      when "Imperva"
        "Imperva/Incapsula block page"
      when "AWS WAF"
        "AWS WAF block page"
      when "F5 BIG-IP"
        "F5 BIG-IP block page"
      when "Wordfence"
        "Wordfence block page"
      when "ModSecurity"
        "ModSecurity block page"
      else
        title || "edge block page"
      end
    end
    private_class_method :vendor_summary

    def self.first_sentence(body)
      text = visible_text(body, max: 300)
      text.split(/(?<=[.!?])\s+/).first
    end
    private_class_method :first_sentence

    def self.visible_text(body, max: 300)
      text = body.to_s
                 .gsub(/<script\b[^>]*>.*?<\/script>/mi, " ")
                 .gsub(/<style\b[^>]*>.*?<\/style>/mi, " ")
                 .gsub(/<[^>]+>/, " ")
      text = CGI.unescapeHTML(text)
      Sanitize.terminal(text, max: max)
    end
    private_class_method :visible_text
  end
end
